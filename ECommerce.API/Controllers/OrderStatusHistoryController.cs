
using System.Security.Claims;
using ECommerce.API.Data;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;

namespace ECommerce.API.Controllers;

[ApiController]
[Route("api/[controller]")]
[Authorize]
public class OrderStatusHistoryController : ControllerBase
{
    private readonly ApplicationDbContext _context;

    public OrderStatusHistoryController(ApplicationDbContext context)
    {
        _context = context;
    }

    private int CurrentUserId =>
        int.Parse(User.FindFirstValue(ClaimTypes.NameIdentifier)!);

    private bool IsAdmin => User.IsInRole("Admin");

    // GET: api/OrderStatusHistory
    [HttpGet]
    [Authorize(Roles = "Admin")]
    public async Task<IActionResult> GetAll()
    {
        var history = await _context.OrderStatusHistories
            .AsNoTracking()
            .OrderByDescending(h => h.ChangedAt)
            .Select(h => new
            {
                h.OrderStatusHistoryId,
                h.OrderId,
                h.OldStatus,
                h.NewStatus,
                h.ChangedByUserId,
                h.Comment,
                h.ChangedAt
            })
            .ToListAsync();

        return Ok(history);
    }

    // GET: api/OrderStatusHistory/1
    [HttpGet("{id}")]
    public async Task<IActionResult> GetById(long id)
    {
        var query = _context.OrderStatusHistories
            .AsNoTracking()
            .Where(h => h.OrderStatusHistoryId == id);

        if (!IsAdmin)
            query = query.Where(h => h.Order.UserId == CurrentUserId);

        var history = await query
            .Select(h => new
            {
                h.OrderStatusHistoryId,
                h.OrderId,
                h.OldStatus,
                h.NewStatus,
                h.Comment,
                h.ChangedAt
            })
            .FirstOrDefaultAsync();

        if (history == null)
            return NotFound(new { message = "Order status history not found." });

        return Ok(history);
    }

    // POST, PUT and DELETE are intentionally disabled.
    // History entries should be generated by trusted backend workflows.
}
